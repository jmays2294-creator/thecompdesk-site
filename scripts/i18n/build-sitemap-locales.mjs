#!/usr/bin/env node
/**
 * Add the locale URLs to sitemap.xml, with xhtml:link hreflang alternates on each entry.
 *
 * The pages already carry hreflang in their <head>; repeating it in the sitemap is the
 * belt-and-braces form Google documents, and it lets the alternates be discovered without
 * fetching all ten pages first.
 *
 * Only touches a clearly-delimited generated block, so the hand-maintained English
 * entries above it (which include /learn/ pages that are deliberately NOT in the i18n
 * manifest) are never rewritten.
 *
 *   node scripts/i18n/build-sitemap-locales.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(new URL('../../', import.meta.url).pathname);
const ORIGIN = 'https://thecompdesk.com';
const CHECK = process.argv.includes('--check');

const locales = JSON.parse(fs.readFileSync(path.join(ROOT, 'i18n/locales.json'), 'utf8')).locales;
const pages = JSON.parse(fs.readFileSync(path.join(ROOT, 'i18n/pages.json'), 'utf8')).pages;

const urlFor = (route, loc) => {
  const prefix = loc.prefix || '';
  return route === '/' ? `${ORIGIN}${prefix}/` : `${ORIGIN}${prefix}${route}`;
};

const START = '  <!-- i18n:locale-urls (generated by scripts/i18n/build-sitemap-locales.mjs) -->';
const END = '  <!-- /i18n:locale-urls -->';

const lines = [START];
for (const page of pages) {
  for (const loc of locales) {
    if (!loc.prefix) continue;                       // English entries stay hand-maintained above
    lines.push('  <url>');
    lines.push(`    <loc>${urlFor(page.route, loc)}</loc>`);
    for (const alt of locales) {
      lines.push(`    <xhtml:link rel="alternate" hreflang="${alt.code}" href="${urlFor(page.route, alt)}"/>`);
    }
    lines.push(`    <xhtml:link rel="alternate" hreflang="x-default" href="${urlFor(page.route, locales[0])}"/>`);
    lines.push('    <changefreq>monthly</changefreq>');
    lines.push('    <priority>0.6</priority>');
    lines.push('  </url>');
  }
}
lines.push(END);
const block = lines.join('\n');

let xml = fs.readFileSync(path.join(ROOT, 'sitemap.xml'), 'utf8');

// The xhtml namespace is required for the alternate links to be valid.
if (!xml.includes('xmlns:xhtml=')) {
  xml = xml.replace('<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n        xmlns:xhtml="http://www.w3.org/1999/xhtml">');
}

const existing = new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\n?`);
xml = existing.test(xml) ? xml.replace(existing, block + '\n') : xml.replace('</urlset>', block + '\n\n</urlset>');

const cur = fs.readFileSync(path.join(ROOT, 'sitemap.xml'), 'utf8');
if (CHECK) {
  if (cur !== xml) { console.error('STALE — sitemap locale block is out of date. Run without --check.'); process.exit(1); }
  console.log('OK — sitemap locale block is current.');
} else {
  fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), xml);
  const n = pages.length * locales.filter((l) => l.prefix).length;
  console.log(`sitemap.xml: ${n} locale URLs (${pages.length} pages × ${locales.filter((l) => l.prefix).length} locales), each with ${locales.length + 1} alternates`);
}
